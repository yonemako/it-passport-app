import streamlit as st

st.title("🧠 ITパスポート 魔法の暗記アプリ")
st.write("難しい用語を、日常の例えと図解で一発暗記！合格を目指してどんどん覚えよう！")

# 選択できる用語を大幅追加
selected_term = st.selectbox(
    "覚えたい用語を選んでください",
    [
        "Cookie（クッキー）", 
        "DNS", 
        "WBS", 
        "CPUとメモリ（主記憶装置）", 
        "SQL（エスキューエル）", 
        "ペネトレーションテスト"
    ]
)

if st.button("✨ 魔法の解説を表示する"):
    if selected_term == "Cookie（クッキー）":
        st.subheader("🍪 Cookie（クッキー）")
        st.write("**一言で言うと**: ネット上の『私の身分証・おぼえ書きタグ』")
        st.info("💡 日常の例え：常連のカフェで店員さんが「いつものね！」と覚えていてくれるようなもの。ブラウザに小さなメモを貼っておく仕組みです。")
        st.text("""
【テキスト図解】
[スマホ] ── 1回目ログイン ──> [Webサーバー]
         <── Cookieを預かる ──┘
        """)
        st.warning("⚠️ 引っ掛けポイント：サーバー側ではなく、自分のブラウザ（手元）に保存されます！")

    elif selected_term == "DNS":
        st.subheader("🌐 DNS（Domain Name System）")
        st.write("**一言で言うと**: ネット上の『電話帳』")
        st.info("💡 日常の例え：『Amazonに行きたい！』と入力したとき、裏で数字の住所（IPアドレス）に変換して案内してくれる親切な案内人です。")
        st.warning("⚠️ 引っ掛けポイント：ドメイン名（文字）からIPアドレス（数字）に変換するのがDNSの役割です。")

    elif selected_term == "WBS":
        st.subheader("📊 WBS（Work Breakdown Structure）")
        st.write("**一言で言うと**: プロジェクトの『巨大なスイカの解体マップ』")
        st.info("💡 日常の例え：大きな仕事を小さなパーツに細かく分解して、誰が・いつまでにやるかを整理する設計図です。")
        st.warning("⚠️ 引っ掛けポイント：スケジュール（ガントチャートなど）を作る「前」に、作業を階層的に分解する作業です。")

    elif selected_term == "CPUとメモリ（主記憶装置）":
        st.subheader("💻 CPU と メモリ（主記憶装置）")
        st.write("**一言で言うと**: 「職人（CPU）」と「作業机（メモリ）」")
        st.info("💡 日常の例え：CPUはバリバリ働く「料理人（頭脳）」、メモリは一度に広げられる「調理台の広さ」。調理台が広いほど、たくさんの料理を同時に作れます。")
        st.warning("⚠️ 引っ掛けポイント：電源を切るとメモリの中身はすべて消えます（揮発性）！")

    elif selected_term == "SQL（エスキューエル）":
        st.subheader("🗄️ SQL（Structured Query Language）")
        st.write("**一言で言うと**: データベース（電子書庫）にお願いをするための『専用の呪文』")
        st.info("💡 日常の例え：図書館の巨大な検索システムで「2026年出版の本を全部出して！」と司書さんにお願いする言葉のようなもの。")
        st.warning("⚠️ 引っ掛けポイント：データベースを「作る・管理する」ソフトの名前ではなく、データベースに命令を出す「言語」の名前です。")

    elif selected_term == "ペネトレーションテスト":
        st.subheader("🕵️‍♂️ ペネトレーションテスト（侵入テスト）")
        st.write("**一言で言うと**: 本物のハッカーになりきって『セキュリティの弱点』を探す模擬攻撃")
        st.info("💡 日常の例え：自宅の鍵が本当に泥棒に破られないか、専門の鍵師に頼んでわざとピッキングしてもらうようなもの。")
        st.warning("⚠️ 引っ掛けポイント：単なる自動の脆弱性診断ツールではなく、実際に攻撃を仕掛けてシステムが突破されるか試す高度なテストです。")
